"""Explicit, byte-bound publication grants. Archival existence is not permission."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = 'data/public-media-rights.json'
MEDIA_EXTENSIONS = {'.gif','.png','.jpg','.jpeg','.webp','.svg','.mp4','.webm','.mov','.avif','.mp3','.wav','.ogg'}
LFS_HEADER = b'version https://git-lfs.github.com/spec/v1'


def grants(root: Path = ROOT) -> dict[str, dict]:
    path = root / REGISTRY
    if not path.is_file():
        return {}
    records = json.loads(path.read_text(encoding='utf-8')).get('assets', [])
    result = {}
    for item in records:
        key = item.get('path', '')
        if key in result:
            raise ValueError(f'duplicate public-media grant: {key}')
        result[key] = item
    return result


def is_public_asset(path: str, root: Path = ROOT) -> bool:
    """Default deny; a label or a pointer is never proof of playable content."""
    if not path or not isinstance(path, str) or '\\' in path:
        return False
    pure = PurePosixPath(path)
    if pure.is_absolute() or '..' in pure.parts or str(pure) != path or ':' in path:
        return False
    item = grants(root).get(path)
    if not item or any(not item.get(k) for k in ('sha256','credit','source_url','license','evidence_url','changes')):
        return False
    if item['license'] != 'project-created' and not item.get('license_url'):
        return False
    file = root / path
    if not file.is_file() or any(p.is_symlink() for p in [file, *file.parents] if p != root.parent):
        return False
    try:
        file.resolve().relative_to(root.resolve())
    except ValueError:
        return False
    return hashlib.sha256(file.read_bytes()).hexdigest() == item['sha256']


def public_docs_paths(root: Path = ROOT) -> list[str]:
    return sorted(path.removeprefix('docs/') for path in grants(root)
                  if path.startswith('docs/') and is_public_asset(path,root))


def write_browser_registry(root: Path = ROOT) -> None:
    target = root / 'docs/data/public-media.js'
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text('/* Generated by tools/media_policy.py; exact approved local paths only. */\n'
                      'window.PUBLIC_MEDIA_PATHS = '+json.dumps(public_docs_paths(root),indent=2)+';\n',encoding='utf-8')

if __name__ == '__main__':
    write_browser_registry()
